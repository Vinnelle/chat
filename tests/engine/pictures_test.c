void test_images(double *t) {
    (void)t;
    static const uint8_t bg[3] = { 0, 0, 0 };
    static const uint8_t want[8][3] = { { 255, 0, 0 }, { 0, 255, 0 }, { 0, 0, 255 }, { 255, 255, 255 },
                                        { 0, 0, 0 }, { 128, 128, 128 }, { 10, 20, 30 }, { 200, 100, 50 } };
    image_thumb_t th;
    char why[160];
    CHECK(image_thumbnail(PNG_4X2, sizeof PNG_4X2, 64, 48, bg, &th, why, sizeof why) == 0 && th.w == 4 && th.h == 2
          && th.src_w == 4 && th.src_h == 2 && memcmp(th.rgb, want, sizeof want) == 0, "the 4x2 PNG: %s", why);
    image_thumb_free(&th);
    // Shrunk to one pixel: the average of all eight.
    CHECK(image_thumbnail(PNG_4X2, sizeof PNG_4X2, 1, 1, bg, &th, why, sizeof why) == 0 && th.w == 1 && th.h == 1,
          "the 4x2 PNG at 1x1: %s", why);
    if (th.rgb) CHECK(th.rgb[0] == 106 && th.rgb[1] == 95 && th.rgb[2] == 90, "1x1 average %u,%u,%u", th.rgb[0], th.rgb[1], th.rgb[2]);
    image_thumb_free(&th);
    CHECK(image_thumbnail(JPEG_GREY, sizeof JPEG_GREY, 64, 48, bg, &th, why, sizeof why) == 0 && th.w == 8 && th.h == 8,
          "the grey JPEG: %s", why);
    int off = 0;
    for (int i = 0; th.rgb && i < 8 * 8 * 3; i++) off += th.rgb[i] < 198 || th.rgb[i] > 202;
    CHECK(off == 0, "the grey JPEG came out %d samples off 200", off);
    image_thumb_free(&th);

    // Damage of every kind is refused with a reason, never read past.
    uint8_t bad[sizeof PNG_4X2];
    memcpy(bad, PNG_4X2, sizeof bad);
    bad[sizeof bad - 20] ^= 0x40;
    CHECK(image_thumbnail(bad, sizeof bad, 64, 48, bg, &th, why, sizeof why) != 0 && why[0], "a damaged PNG decoded");
    for (size_t cut = 0; cut < sizeof PNG_4X2; cut += 7)
        CHECK(image_thumbnail(PNG_4X2, cut, 64, 48, bg, &th, why, sizeof why) != 0, "a PNG cut to %zu bytes decoded", cut);
    for (size_t cut = 0; cut < sizeof JPEG_GREY - 2; cut += 11)
        CHECK(image_thumbnail(JPEG_GREY, cut, 64, 48, bg, &th, why, sizeof why) != 0 || (image_thumb_free(&th), 1),
              "a JPEG cut to %zu bytes", cut);
    CHECK(image_thumbnail((const uint8_t *)"GIF89a", 6, 64, 48, bg, &th, why, sizeof why) != 0, "a GIF cut short decoded");
    CHECK(image_kind(PNG_4X2, sizeof PNG_4X2) && strcmp(image_kind(PNG_4X2, sizeof PNG_4X2), "png") == 0
          && strcmp(image_kind(JPEG_GREY, sizeof JPEG_GREY), "jpeg") == 0
          && strcmp(image_kind(GIF_4X2, sizeof GIF_4X2), "gif") == 0, "images weren't told apart");

    // A GIF: the see-through colour is the background.
    static const uint8_t grey[3] = { 30, 30, 30 };
    uint8_t gwant[8][3];
    memcpy(gwant, want, sizeof gwant);
    memcpy(gwant[7], grey, 3);
    CHECK(image_thumbnail(GIF_4X2, sizeof GIF_4X2, 64, 48, grey, &th, why, sizeof why) == 0 && th.w == 4 && th.h == 2
          && memcmp(th.rgb, gwant, sizeof gwant) == 0, "the 4x2 GIF: %s", why);
    image_thumb_free(&th);
    // The same frame a row down a screen two rows taller: the screen around it is background too.
    uint8_t gif[sizeof GIF_4X2];
    memcpy(gif, GIF_4X2, sizeof gif);
    gif[8] = 4;    // the screen's height
    gif[48] = 1;   // the frame's top
    uint8_t screen[16][3];
    for (int i = 0; i < 16; i++) memcpy(screen[i], i >= 4 && i < 12 ? gwant[i - 4] : grey, 3);
    CHECK(image_thumbnail(gif, sizeof gif, 64, 48, grey, &th, why, sizeof why) == 0 && th.w == 4 && th.h == 4
          && memcmp(th.rgb, screen, sizeof screen) == 0, "the GIF on a bigger screen: %s", why);
    image_thumb_free(&th);
    // Cut before its image data it's refused; cut anywhere it's never read past.
    for (size_t cut = 0; cut < sizeof GIF_4X2; cut++) {
        int rc = image_thumbnail(GIF_4X2, cut, 64, 48, grey, &th, why, sizeof why);
        CHECK(rc != 0 || cut > 56, "a GIF cut to %zu bytes decoded", cut);
        if (rc == 0) image_thumb_free(&th);
    }

    // A progressive JPEG comes out the same as the baseline one, full size and at an eighth.
    image_thumb_t base;
    for (int small = 0; small < 2; small++) {
        int mw = small ? 3 : 64, mh = small ? 2 : 48;
        CHECK(image_thumbnail(JPEG_BASE, sizeof JPEG_BASE, mw, mh, bg, &base, why, sizeof why) == 0, "the baseline JPEG: %s", why);
        CHECK(image_thumbnail(JPEG_PROG, sizeof JPEG_PROG, mw, mh, bg, &th, why, sizeof why) == 0, "the progressive JPEG: %s", why);
        CHECK(th.rgb && base.rgb && th.w == base.w && th.h == base.h && th.w == (small ? 3 : 20) && th.h == (small ? 2 : 12)
              && memcmp(th.rgb, base.rgb, (size_t)th.w * (size_t)th.h * 3) == 0,
              "the progressive JPEG at %dx%d isn't the baseline one", mw, mh);
        image_thumb_free(&th);
        image_thumb_free(&base);
    }
    for (size_t cut = 0; cut < sizeof JPEG_PROG - 2; cut += 13)
        CHECK(image_thumbnail(JPEG_PROG, cut, 64, 48, bg, &th, why, sizeof why) != 0 || (image_thumb_free(&th), 1),
              "a progressive JPEG cut to %zu bytes", cut);
}

